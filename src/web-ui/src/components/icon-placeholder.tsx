export type IconPlaceholderProps = {
  lucide?: string;
  tabler?: string;
  hugeicons?: string;
  phosphor?: string;
  remixicon?: string;
} & React.ComponentProps<"svg">;

export function IconPlaceholder(props: IconPlaceholderProps) {
  const { lucide, tabler, hugeicons, phosphor, remixicon, ...rest } = props;

  // Priority: lucide > hugeicons > phosphor > remixicon > tabler
  const iconName = lucide || hugeicons || phosphor || remixicon || tabler;
  const IconComponent = lucideIcons[iconName as keyof typeof lucideIcons];

  if (!IconComponent) {
    console.warn(`Icon "${iconName}" not found in lucideIcons registry`);
    return <span {...rest} aria-hidden="true" />;
  }

  return <IconComponent {...rest} />;
}